const stack = [];
export function openModal({ title, body, actions = [], dismissible = true, className = '' }) {
  const close = (result) => { backdrop.remove(); stack.splice(stack.indexOf(api), 1); api.resolve?.(result); };
  const api = { close };
  const buttons = actions.map((a) => h('button', {
    class: `btn ${a.kind === 'primary' ? 'btn-primary' : a.kind === 'gold' ? 'btn-gold' : a.kind === 'danger' ? 'btn-danger' : 'btn-ghost'}`, type: 'button',
    onClick: async (e) => {
      if (!a.onClick) return close(a.value);
      const btn = e.currentTarget; btn.disabled = true;
      try { const r = await a.onClick(api); if (r !== false && a.closes !== false) close(r); } finally { btn.disabled = false; }
    },
  }, a.label));
  const modal = h('div', { class: `modal ${className}`, role: 'dialog', 'aria-modal': 'true', 'aria-label': title },
    h('div', { class: 'modal-head' }, h('h3', null, title),
      dismissible && h('button', { class: 'icon-btn', 'aria-label': 'Close', type: 'button', onClick: () => close(null) }, icon('x'))),
    h('div', { class: 'modal-body' }, body),
    buttons.length ? h('div', { class: 'modal-foot' }, buttons) : null);
  const backdrop = h('div', { class: 'backdrop', onMouseDown: (e) => { if (dismissible && e.target === backdrop) close(null); } }, modal);
  api.el = modal; api.dismissible = dismissible;
  api.promise = new Promise((res) => { api.resolve = res; });
  document.body.append(backdrop); stack.push(api);
  setTimeout(() => (modal.querySelector('input,select,textarea,.btn-primary,.btn-gold,button') || modal).focus(), 30);
  return api;
}
document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape' && stack.length && stack[stack.length - 1].dismissible) stack[stack.length - 1].close(null);
});
export const anyModalOpen = () => stack.length > 0;

export function confirmDialog({ title, message, confirmLabel = 'Confirm', danger = false }) {
  const m = openModal({
    title, body: h('p', { style: 'margin:6px 0 10px;color:var(--ink-2)' }, message),
    actions: [{ label: 'Cancel', value: false }, { label: confirmLabel, kind: danger ? 'danger' : 'primary', value: true }],
  });
  return m.promise.then((v) => v === true);
}

